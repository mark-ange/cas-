create table public.barangays (
  id bigint generated by default as identity primary key,
  city text not null,
  name text not null,
  unique (city, name)
);

create table public.puroks (
  id bigint generated by default as identity primary key,
  barangay_id bigint not null references public.barangays (id) on delete restrict,
  name text not null,
  unique (barangay_id, name),
  unique (id, barangay_id)
);

insert into public.barangays (city, name)
select 'Cagayan de Oro City', name
from unnest(array[
  'Agusan', 'Balulang', 'Bugo', 'Carmen', 'Gusa', 'Iponan', 'Kauswagan',
  'Lumbia', 'Macabalan', 'Macasandig', 'Nazareth', 'Patag', 'Puerto'
]) as names(name)
on conflict (city, name) do nothing;

insert into public.puroks (barangay_id, name)
select barangays.id, 'Purok ' || numbers.number
from public.barangays
cross join generate_series(1, 10) as numbers(number)
where barangays.city = 'Cagayan de Oro City'
on conflict (barangay_id, name) do nothing;

alter table public.profiles
  add column if not exists barangay_id bigint references public.barangays (id) on delete restrict,
  add column if not exists purok_id bigint;

update public.profiles as profiles
set barangay_id = barangays.id
from public.barangays as barangays
where profiles.barangay_id is null
  and lower(trim(profiles.barangay)) = lower(barangays.name)
  and lower(trim(coalesce(profiles.city, barangays.city))) = lower(barangays.city);

update public.profiles as profiles
set purok_id = puroks.id
from public.puroks as puroks
where profiles.purok_id is null
  and profiles.barangay_id = puroks.barangay_id
  and lower(puroks.name) = lower(
    case
      when trim(coalesce(profiles.purok, '')) ~* '^purok[[:space:]]+[0-9]+$'
        then trim(profiles.purok)
      when trim(coalesce(profiles.purok, '')) ~ '^[0-9]+$'
        then 'Purok ' || trim(profiles.purok)
      else ''
    end
  );

alter table public.profiles
  add constraint profiles_purok_barangay_fk
  foreign key (purok_id, barangay_id)
  references public.puroks (id, barangay_id)
  on delete restrict;

create table public.advisory_areas (
  advisory_id bigint not null references public.advisories (id) on delete cascade,
  purok_id bigint not null references public.puroks (id) on delete restrict,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  primary key (advisory_id, purok_id)
);

insert into public.advisory_areas (advisory_id, purok_id, latitude, longitude)
select advisories.id, puroks.id,
  case
    when area_pin.value ->> 'latitude' ~ '^-?[0-9]+(\.[0-9]+)?$'
      then (area_pin.value ->> 'latitude')::double precision
  end,
  case
    when area_pin.value ->> 'longitude' ~ '^-?[0-9]+(\.[0-9]+)?$'
      then (area_pin.value ->> 'longitude')::double precision
  end
from public.advisories
cross join lateral jsonb_array_elements(
  case
    when jsonb_typeof(advisories.area_locations) = 'array' then advisories.area_locations
    else '[]'::jsonb
  end
) as area_pin(value)
join public.barangays
  on lower(barangays.name) = lower(split_part(area_pin.value ->> 'area', ' · ', 1))
join public.puroks
  on puroks.barangay_id = barangays.id
  and lower(puroks.name) = lower(split_part(area_pin.value ->> 'area', ' · ', 2))
where jsonb_typeof(advisories.area_locations) = 'array'
  and area_pin.value ->> 'latitude' ~ '^-?[0-9]+(\.[0-9]+)?$'
  and area_pin.value ->> 'longitude' ~ '^-?[0-9]+(\.[0-9]+)?$'
on conflict (advisory_id, purok_id) do nothing;

create index profiles_location_idx on public.profiles (barangay_id, purok_id)
  where role = 'resident';
create index advisory_areas_purok_idx on public.advisory_areas (purok_id, advisory_id);

alter table public.barangays enable row level security;
alter table public.puroks enable row level security;
alter table public.advisory_areas enable row level security;

create policy barangays_read_public
  on public.barangays for select to anon, authenticated using (true);
create policy puroks_read_public
  on public.puroks for select to anon, authenticated using (true);

create policy advisory_areas_read_published_or_utility_admin
  on public.advisory_areas for select to anon, authenticated
  using (
    exists (
      select 1 from public.advisories
      where advisories.id = advisory_areas.advisory_id
        and (
          advisories.publication_status = 'published'
          or public.is_utility_admin(advisories.utility)
        )
    )
  );
create policy advisory_areas_manage_utility
  on public.advisory_areas for all to authenticated
  using (
    exists (
      select 1 from public.advisories
      where advisories.id = advisory_areas.advisory_id
        and public.is_utility_admin(advisories.utility)
    )
  )
  with check (
    exists (
      select 1 from public.advisories
      where advisories.id = advisory_areas.advisory_id
        and public.is_utility_admin(advisories.utility)
    )
  );
