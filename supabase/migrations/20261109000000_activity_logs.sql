create table public.activity_logs (
  id bigint generated by default as identity primary key,
  utility text not null check (utility in ('CEPALCO', 'Water District')),
  actor_id uuid references public.profiles (id) on delete set null,
  advisory_id bigint references public.advisories (id) on delete set null,
  action text not null,
  summary text not null,
  created_at timestamptz not null default now()
);

create index activity_logs_utility_created_idx
  on public.activity_logs (utility, created_at desc);

alter table public.activity_logs enable row level security;

create policy activity_logs_read_utility_admin
  on public.activity_logs for select to authenticated
  using (public.is_utility_admin(utility));

create policy activity_logs_create_utility_admin
  on public.activity_logs for insert to authenticated
  with check (
    actor_id = (select auth.uid())
    and public.is_utility_admin(utility)
  );

grant select, insert on public.activity_logs to authenticated;
grant usage, select on sequence public.activity_logs_id_seq to authenticated;
